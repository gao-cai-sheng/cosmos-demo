/** 把 v 夹在 [a, b] 之间 */
export const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);

/** 线性插值 */
export const lerp = (a, b, t) => a + (b - a) * t;

/** 平滑阶跃：在 [e0, e1] 之间用 3t²−2t³ 过渡，两端导数为零。
    直接用线性插值的地方，参数越过阈值时会有一个能看出来的折角。 */
export function sstep(e0, e1, v) {
  const t = clamp((v - e0) / (e1 - e0 || 1e-9), 0, 1);
  return t * t * (3 - 2 * t);
}

/** mulberry32。确定性伪随机：同一个种子永远给出同一串数。
    程序化纹理必须用它而不是 Math.random —— 否则每次刷新
    车身上的褶皱和污渍都不一样，就没法做视觉对比了。 */
export function makeRNG(seed) {
  let a = seed | 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
